);

CREATE TABLE public.filiacoes_partidarias (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  deputado_id integer NOT NULL REFERENCES public.deputados(id) ON DELETE CASCADE,
  sigla_partido varchar(50) NOT NULL,
  nome_partido varchar(150),
  data_inicio varchar(50),
  data_fim varchar(50),
  fonte varchar(100) DEFAULT 'Câmara dos Deputados'
);

CREATE TABLE public.deputado_historico (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  deputado_id integer NOT NULL REFERENCES public.deputados(id) ON DELETE CASCADE,
  data_hora varchar(50),
  sigla_partido varchar(50),
  situacao varchar(100),
  condicao_eleitoral varchar(100),
  descricao_status text,
  legislatura integer
);

CREATE TABLE public.proposicoes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  camara_id integer NOT NULL UNIQUE,
