-- Snitch: bootstrap completo para um projeto Supabase NOVO / banco vazio.
-- Este script inclui as tabelas atuais do ORM + cache híbrido.
-- Execute UMA vez no SQL Editor do Supabase (como postgres).
-- NÃO execute sobre banco existente: use as migrações Alembic para upgrades.
-- Sem acesso direto de anon/authenticated/service_role ao banco: a API pública
-- passa pelo FastAPI, com DATABASE_URL disponível somente no servidor.

BEGIN;

CREATE TABLE public.legislaturas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  camara_id integer NOT NULL UNIQUE,
  numero integer NOT NULL UNIQUE,
  data_inicio varchar(50),
  data_fim varchar(50),
  ano_inicio integer,
  ano_fim integer
);

CREATE TABLE public.deputados (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  camara_id integer NOT NULL UNIQUE,
  nome_parlamentar varchar(255) NOT NULL,
  nome_civil varchar(255),
  sigla_partido varchar(50),
  uf varchar(10),
  url_foto varchar(500),
  situacao varchar(100),
  condicao_eleitoral varchar(100),
  descricao_status text,
  email varchar(255),
  legislatura integer,
  gabinete_predio varchar(50),
  gabinete_sala varchar(50),
  gabinete_andar varchar(50),
  gabinete_telefone varchar(50),
  data_nascimento varchar(50),
  municipio_nascimento varchar(100),
  uf_nascimento varchar(10),
  escolaridade varchar(100),
  rede_social json,
  url_website varchar(500),
  uri varchar(500),
  dados_raw json,
  updated_at timestamptz DEFAULT now()
);

CREATE TABLE public.mandatos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  deputado_id integer NOT NULL REFERENCES public.deputados(id) ON DELETE CASCADE,
  legislatura_id integer,
