CREATE TABLE public.proposicao_temas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proposicao_id integer NOT NULL REFERENCES public.proposicoes(id) ON DELETE CASCADE,
  tema_id integer NOT NULL REFERENCES public.temas(id) ON DELETE CASCADE,
  relevancia integer DEFAULT 0
);

CREATE TABLE public.tramitacoes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proposicao_id integer NOT NULL REFERENCES public.proposicoes(id) ON DELETE CASCADE,
  data_hora varchar(50),
  sequencia integer NOT NULL DEFAULT 1,
  descricao_tramitacao varchar(255),
  despacho text,
  orgao varchar(100),
  situacao varchar(150),
  regime varchar(100),
  url_documento varchar(500)
);

CREATE TABLE public.votacoes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
