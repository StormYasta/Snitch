  bancada varchar(100) NOT NULL,
  orientacao_voto varchar(50) NOT NULL
);

CREATE TABLE public.votos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  votacao_id integer NOT NULL REFERENCES public.votacoes(id) ON DELETE CASCADE,
  deputado_id integer NOT NULL REFERENCES public.deputados(id) ON DELETE CASCADE,
  tipo_voto varchar(50) NOT NULL,
  data_hora varchar(50),
  sigla_partido_momento varchar(50),
